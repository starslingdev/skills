"""OPT82 keeps its results through OPT84's shared command resolver (maintainers-only).

`fixtures/opt82_resolver_snapshot.json` (plain JSON, ~1.07 MB; 128 resolver calls, 92 detector
calls) holds every distinct call the OPT82 test module makes to `_opt82_resolve_lint` and
`_detect_opt82_type_aware_lint`, recorded with its output against the engine at main a7c2db4,
before the resolver was generalized. The replay tests feed those arguments to today's engine
and require byte-identical output. The snapshot is regenerated by
`maintainers/ci-speedup/scripts/record_opt82_resolver_snapshot.py`; the last test proves the
generator reproduces the committed file byte for byte. It lives here, not under the installable
skill, because it is maintainer regression data (the install-surface guard enforces that).
"""
from __future__ import annotations

import json
from pathlib import Path

import collect_runs as cr
import record_opt82_resolver_snapshot as recorder

_SNAPSHOT = Path(__file__).resolve().parent / "fixtures" / "opt82_resolver_snapshot.json"
_RESOLVE_CALLS = 128
_DETECT_CALLS = 92


def _snapshot():
    return json.loads(_SNAPSHOT.read_text(encoding="utf-8"))


def test_opt82_resolver_results_are_byte_identical_to_the_pre_refactor_snapshot():
    snap = _snapshot()
    assert len(snap["resolve"]) == _RESOLVE_CALLS
    for e in snap["resolve"]:
        cmd, wd, sbd, chain, depth, unreadable, runner = e["args"]
        got = cr._opt82_resolve_lint(cmd, wd, sbd, chain, depth, frozenset(unreadable),
                                     runner)
        assert recorder._norm(got) == e["out"], e["args"]


def test_opt82_detector_results_are_byte_identical_to_the_pre_refactor_snapshot():
    snap = _snapshot()
    assert len(snap["detect"]) == _DETECT_CALLS
    for e in snap["detect"]:
        wf, jpr, crit, doc, block, idx = e["args"]
        w = None if e["withheld_in"] is None else dict(e["withheld_in"])
        c = None if e["cands_in"] is None else list(e["cands_in"])
        got = cr._detect_opt82_type_aware_lint(wf, jpr, crit, doc, block, idx, w, c)
        assert recorder._norm(got) == e["out"]
        assert recorder._norm(w) == e["withheld"] and recorder._norm(c) == e["cands"]


def test_the_committed_snapshot_is_in_the_recorders_one_serialization():
    text = _SNAPSHOT.read_text(encoding="utf-8")
    assert text == recorder.dumps(json.loads(text))


def test_recording_reproduces_the_committed_snapshot_byte_for_byte(tmp_path):
    out = tmp_path / "opt82_resolver_snapshot.json"
    recorder.record(out)
    assert out.read_bytes() == _SNAPSHOT.read_bytes(), (
        "re-recording the OPT82 resolver snapshot changed it: OPT82's tests or fixtures "
        "changed. If on purpose, re-record with "
        "maintainers/ci-speedup/scripts/record_opt82_resolver_snapshot.py and commit it")
