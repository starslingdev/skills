"""Tests for the typed claims layer (plan 002a headline family + plan 007 framing family).

  (a) round-trip     — `ClaimSet.add()` returns each claim's `rendered`; `to_json()`
                       serializes both claims + the `families_migrated` key.
  (b) manifest-write — a real `blocking_path.main()` render writes `<report>.claims.json`
                       beside the report, carrying a `headline_slowest` claim (and, plan
                       007, the migrated `pole_role_line` / `pole_gate_prompt` framing
                       claims, plus the Tier-2 runner-minute family) whose `rendered`
                       sentence appears verbatim in the report.
  (c) comparator red/green — `verify_report.check_headline_slowest_matches_stamp` PASSES
                       on the good manifest and FAILS when the manifest's
                       `headline_slowest.subject` is corrupted off the stamped
                       `critical_path_check`. (The committed form of the manual
                       red/green proof from this plan.)
  (d) text floor (plan 007) — a crafted but internally-consistent manifest cannot launder
                       a prose headline that names a different check than the stamp.

The framing-vocabulary coverage check and the anti-unregistered-claim source lint (plan
007) live in `test_verify_report_self.py`.

(b)/(c) reuse the offline-e2e gh-replay fixture corpus (fixtures/gh_replay/): the
same synthetic repo + recorded gh responses `test_offline_pipeline_e2e.py` drives,
so the findings.json is generated by the REAL pipeline, offline and deterministic.

Run: pytest -v skills/ci-speedup/tests/test_claims_layer.py
"""
